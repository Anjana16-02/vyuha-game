export function titleForLevel(level: number): string {
  if (level >= 20) return LEVEL_TITLES[20];
  if (level >= 10) return LEVEL_TITLES[10];
  if (level >= 5) return LEVEL_TITLES[5];
  if (level >= 3) return LEVEL_TITLES[3];
  if (level >= 2) return LEVEL_TITLES[2];
  return LEVEL_TITLES[1];
}

export function xpToNext(level: number): number {
  return Math.round(180 + level * 90 + level * level * 12);
}

